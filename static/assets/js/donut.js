const donutChart1 = document.getElementById('donutChart1').getContext('2d');
const donutChart1Data = {
    datasets: [{
        label: 'Dataset 1',
        data: [300, 100],
        backgroundColor: ['#12372a', '#adbc9f']
    }]
};
const donutChart1Config = {
    type: 'doughnut',
    data: donutChart1Data,
    options: {
        plugins: {
            tooltip: {
                enabled: false
            }
        }
    }
};
new Chart(donutChart1, donutChart1Config);

